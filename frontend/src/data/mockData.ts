const DEMO_ANCHOR = Date.parse('2024-10-12T14:40:00Z'); // newest raw demo timestamp
const DEMO_SHIFT = Date.now() - 10 * 60_000 - DEMO_ANCHOR;
const shift = (iso: string) => new Date(Date.parse(iso) + DEMO_SHIFT).toISOString();
const ISO_RE = /^\d{4}-\d{2}-\d{2}T/;

/** Deep-copy demo data with every ISO timestamp moved so the demo always looks recent. */
function recent<T>(value: T): T {
  if (typeof value === 'string') return (ISO_RE.test(value) ? shift(value) : value) as T;
  if (Array.isArray(value)) return value.map(recent) as T;
  if (value && typeof value === 'object') {
    return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, recent(v)])) as T;
  }
  return value;
}

